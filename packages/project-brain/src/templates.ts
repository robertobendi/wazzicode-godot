import path from "node:path";
import type { Brain } from "./brain.js";
import type { KnowledgeBase, KnowledgeEntity, KnowledgeManifest } from "./knowledge.js";

export function renderBrainMarkdown(brain: Brain, manifest?: KnowledgeManifest): string {
  const coverage = manifest?.coverage ?? brain.assets.coverage;
  const lines = [
    "# Godot Project Brain",
    "",
    `> Generated by **Godot Vibe OS** at ${new Date(brain.generatedAt).toISOString()}.`,
    "",
    "## Project",
    "",
    `- Name: ${brain.identity.projectName ?? "(unknown)"}`,
    `- Path: \`${brain.identity.projectPath}\``,
    `- Godot feature version: ${brain.engine.versionHint ?? "(not declared)"}`,
    `- Main scene: ${brain.engine.mainScene ? `\`${brain.engine.mainScene}\`` : "(not set)"}`,
    `- Renderer: ${brain.engine.renderer ?? "(project default)"}`,
    `- .NET: ${brain.engine.usesDotnet ? "enabled" : "not detected"}`,
    "",
    "## Indexed surface",
    "",
    `- Coverage: ${coverage.complete ? "complete" : coverage.truncated ? "truncated" : "incomplete"} (${coverage.scanned}/${coverage.discovered}, cap ${coverage.cap})`,
    `- Scenes: ${brain.assets.scenes.length}`,
    `- Resources: ${brain.assets.resources.length}`,
    `- GDScript files: ${brain.assets.gdScripts.length}`,
    `- C# files: ${brain.assets.csharpScripts.length}`,
    `- Shaders: ${brain.assets.shaders.length}`,
    `- Addons: ${brain.assets.addons.length}`,
    `- Scan/read errors: ${coverage.errors.length}`,
    "",
    "## Godot architecture signals",
    "",
    `- Global classes: ${brain.architecture.namedClasses.length}`,
    `- Autoloads: ${brain.engine.autoloads.map((entry) => entry.name).join(", ") || "none"}`,
    `- Signals: ${brain.architecture.signalCount}`,
    `- Exported properties: ${brain.architecture.exportCount}`,
    `- Tool scripts: ${brain.architecture.toolScripts.length}`,
    `- Input actions: ${brain.engine.inputActions.join(", ") || "none"}`,
    `- Networking API match: ${yesNo(brain.architecture.hasNetworking)}`,
    `- Save API match: ${yesNo(brain.architecture.hasSaveSystem)}`,
    `- Input API match: ${yesNo(brain.architecture.hasInputHandling)}`,
    "",
  ];
  appendPaths(lines, "Scenes", brain.assets.scenes, 40);
  appendPaths(lines, "Autoload scripts", brain.engine.autoloads.map((entry) => entry.path), 30);
  return lines.join("\n");
}

