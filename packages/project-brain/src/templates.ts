function appendPathList(lines: string[], title: string, values: string[], limit: number): void {
  if (!values.length) return;
  lines.push(`### ${title}`, "");
  for (const value of values.slice(0, limit)) lines.push(`- \`${value}\``);
  if (values.length > limit) lines.push(`- …${values.length - limit} more in the canonical JSONL map`);
  lines.push("");
}

function appendEntityPaths(lines: string[], title: string, entities: KnowledgeEntity[], limit: number): void {
  if (!entities.length) return;
  lines.push(`## ${title}`, "");
  for (const entity of entities.slice(0, limit)) lines.push(`- \`${entity.path ?? entity.name}\``);
  if (entities.length > limit) lines.push(`- …${entities.length - limit} more in \`entities.jsonl\``);
  lines.push("");
}

function appendPackages(lines: string[], entities: KnowledgeEntity[]): void {
  if (!entities.length) return;
  lines.push("## Packages", "");
  for (const entity of entities) {
    const version = entity.facts.find((fact) => fact.key === "version")?.value;
    lines.push(`- \`${entity.name}\`${version ? ` @ ${String(version)}` : ""}`);
  }
  lines.push("");
}

function appendTypes(lines: string[], entities: KnowledgeEntity[], limit: number): void {
  const local = entities.filter((entity) => entity.scope !== "external");
  if (!local.length) return;
  lines.push("## Declared types", "");
  for (const entity of local.slice(0, limit)) {
    const declaration = entity.facts.find((fact) => fact.key === "declarationKind")?.value;
    const bases = entity.facts.find((fact) => fact.key === "baseTypes")?.value;
    const signatures = entity.facts
      .filter((fact) => fact.key === "memberSignature")
      .map((fact) => String(fact.value));
    lines.push(`- \`${entity.name}\` (${String(declaration ?? "type")}) — \`${entity.path ?? "(unknown path)"}\`${Array.isArray(bases) && bases.length ? `; bases: ${bases.join(", ")}` : ""}`);
    if (signatures.length) lines.push(`  - members: ${signatures.slice(0, 8).map((value) => `\`${value}\``).join(", ")}`);
  }
  if (local.length > limit) lines.push(`- …${local.length - limit} more in \`entities.jsonl\``);
  lines.push("");
}

function groupByKind(entities: KnowledgeEntity[]): Map<string, KnowledgeEntity[]> {
  const grouped = new Map<string, KnowledgeEntity[]>();
  for (const entity of entities) {
    const values = grouped.get(entity.kind);
    if (values) values.push(entity);
    else grouped.set(entity.kind, [entity]);
  }
  return grouped;
}

function kindSummary(grouped: Map<string, KnowledgeEntity[]>): string {
  return [...grouped]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([kind, values]) => `${kind} ${values.length}`)
    .join(", ");
}

function singleLine(value: string): string {
  return value.replace(/\s+/g, " ").trim();
}

function yesNo(value: boolean): string {
  return value ? "yes" : "no";
}
