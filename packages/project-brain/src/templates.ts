function appendPaths(lines: string[], title: string, values: string[], limit: number): void {
  if (!values.length) return;
  lines.push(`## ${title}`, "");
  for (const value of values.slice(0, limit)) lines.push(`- \`${value}\``);
  if (values.length > limit) lines.push(`- …${values.length - limit} more`);
  lines.push("");
}

function appendEntities(lines: string[], title: string, entities: KnowledgeEntity[], limit: number): void {
  if (!entities.length) return;
  lines.push(`## ${title}`, "");
  for (const entity of entities.slice(0, limit)) lines.push(`- \`${entity.path ?? entity.name}\``);
  if (entities.length > limit) lines.push(`- …${entities.length - limit} more in \`entities.jsonl\``);
  lines.push("");
}

function groupByKind(entities: KnowledgeEntity[]): Map<string, KnowledgeEntity[]> {
  const output = new Map<string, KnowledgeEntity[]>();
  for (const entity of entities) {
    const values = output.get(entity.kind);
    if (values) values.push(entity);
    else output.set(entity.kind, [entity]);
  }
  return new Map([...output].sort(([a], [b]) => a.localeCompare(b)));
}

function classesWithFacts(
  entities: KnowledgeEntity[],
  key: string,
  value: KnowledgeEntity["facts"][number]["value"],
): KnowledgeEntity[] {
  return entities.filter((entity) => entity.facts.some((fact) => fact.key === key && fact.value === value));
}

function yesNo(value: boolean): string {
  return value ? "yes" : "no";
}
