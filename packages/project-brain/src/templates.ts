export function renderKnowledgeIndexMarkdown(brain: KnowledgeBase): string {
  const { manifest, entities, relations } = brain;
  const kinds = groupByKind(entities);
  const relationCounts = new Map<string, number>();
  for (const relation of relations) relationCounts.set(relation.kind, (relationCounts.get(relation.kind) ?? 0) + 1);
  const lines = [
    `# Godot Knowledge Map: ${manifest.project.name}`,
    "",
    `> Schema v${manifest.schemaVersion}; generated ${new Date(manifest.generatedAt).toISOString()}.`,
    "",
    "## Coverage and freshness",
    "",
    `- State: ${manifest.dirty.value ? "dirty" : "clean"}`,
    `- Coverage: ${manifest.coverage.complete ? "complete" : manifest.coverage.truncated ? "truncated" : "incomplete"}`,
    `- Files: ${manifest.coverage.scanned}/${manifest.coverage.discovered}; cap ${manifest.coverage.cap}`,
    `- First-party: ${manifest.coverage.scopes.firstParty.scanned}/${manifest.coverage.scopes.firstParty.discovered}; ${manifest.coverage.counts.firstPartyScripts} scripts`,
    `- Addons: ${manifest.coverage.scopes.addons.scanned}/${manifest.coverage.scopes.addons.discovered}; ${manifest.coverage.counts.addonScripts} scripts`,
    `- Errors: ${manifest.coverage.errors.length}`,
  ];
  if (manifest.coverage.truncated) lines.push("- Boundary: files beyond the explicit scan cap are unknown, not absent.");
  lines.push(
    "",
    "## Graph summary",
    "",
    `- Entities: ${entities.length} (${[...kinds].map(([kind, values]) => `${kind} ${values.length}`).join(", ")})`,
    `- Relations: ${relations.length} (${[...relationCounts].sort(([a], [b]) => a.localeCompare(b)).map(([kind, count]) => `${kind} ${count}`).join(", ") || "none"})`,
    "",
  );
  appendEntities(lines, "Global classes", classesWithFacts(kinds.get("class") ?? [], "globalClass", true), 80);
  appendEntities(lines, "Scenes", kinds.get("scene") ?? [], 50);
  appendEntities(lines, "Resources", kinds.get("resource") ?? [], 50);
  appendEntities(lines, "Modules", kinds.get("module") ?? [], 80);
  appendEntities(lines, "Addons", kinds.get("addon") ?? [], 40);
  lines.push(
    "## Interpretation",
    "",
    "- Text-derived GDScript and Godot resource edges carry provenance and confidence; they are intentionally conservative.",
    "- `extends` represents script inheritance, `references` covers preloads and external resources, and `instantiates` identifies packed-scene instances.",
    "- Query with `queryBrain(projectPath, { query, kinds, limit })` for ranked entities and bounded graph neighbors.",
    "",
  );
  return lines.join("\n");
}

